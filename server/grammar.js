const FIELD = { s: 'surface_form', b: 'basic_form', pos: 'pos', p1: 'pos_detail_1', cf: 'conjugated_form' };
function test(cond, tok) {
  for (const k in cond) if (!cond[k].test(tok[FIELD[k]] || '')) return false;
  return true;
}

// tokens：kuromoji 原始 token。返回 [{ id, n, lv, zh, start, end, text }]（start/end 为 token 下标，end 不含）
export function matchGrammar(tokens) {
  const found = [];
  for (let i = 0; i < tokens.length; i++) {
    for (const r of RULES) {
      if (i + r.seq.length > tokens.length) continue;
      let ok = true;
      for (let k = 0; k < r.seq.length; k++) {
        if (!test(r.seq[k], tokens[i + k])) { ok = false; break; }
      }
      if (!ok) continue;
      let start = i;
      if (r.a && i > 0 && /^(動詞|形容詞|助動詞|名詞)$/.test(tokens[i - 1].pos)) start = i - 1;
      found.push({ r, start, end: i + r.seq.length, core: i, len: r.seq.length });
    }
  }
  // 重叠时：核心部分更长的优先，其次靠前的规则优先
  found.sort((a, b) => b.len - a.len || RULES.indexOf(a.r) - RULES.indexOf(b.r));
  const used = new Set();
  const out = [];
  for (const f of found) {
    let clash = false;
    for (let k = f.core; k < f.end; k++) if (used.has(k)) clash = true;
    if (clash) continue;
    for (let k = f.core; k < f.end; k++) used.add(k);
    out.push({
      id: f.r.id, n: f.r.n, lv: f.r.lv, zh: f.r.zh, start: f.start, end: f.end,
      text: tokens.slice(f.start, f.end).map((t) => t.surface_form).join(''),
    });
  }
  return out.sort((a, b) => a.start - b.start);
}
